import { mkdirSync } from "node:fs";
import { expect, test } from "@playwright/test";
const evidence = new URL("../../../../docs/evidence/ADAPTIVE-20260928/live/", import.meta.url).pathname;
test("live phone QR verifies a synthetic returning adult and keeps a child's identity separate", async ({ page, request }) => {
  test.skip(process.env.CAREFLOW_LIVE !== "1", "Requires the running local clinic and seeded synthetic records.");
  test.setTimeout(60_000);
  const minted = await request.post("http://localhost:3000/api/kiosk/v1/checkin/start/qr", { data: { language: "en" } });
  expect(minted.ok()).toBe(true);
  const entry = await minted.json() as { qr_token: string };
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`/start?l=en#t=${entry.qr_token}`);
  await page.getByRole("button", { name: "Patient ID", exact: true }).click();
  await page.getByRole("textbox", { name: "Patient ID", exact: true }).fill("100001");
  await page.getByRole("checkbox", { name: "I agree to use these details to find my patient record." }).check();
  const lookup = page.waitForResponse(response => response.url().endsWith("/v1/identity/lookup"));
  await page.getByRole("button", { name: "Find my record" }).click();
  expect((await lookup).status()).toBe(200);
  await expect(page.getByText("We found a possible match")).toBeVisible();
  await page.getByRole("textbox", { name: "Year of birth" }).fill("1968");
  const verify = page.waitForResponse(response => response.url().endsWith("/v1/identity/verify"));
  await page.getByRole("button", { name: "Verify my details" }).click();
  expect((await verify).status()).toBe(200);
  await page.getByRole("button", { name: /Myself/ }).click();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  const patientName = await page.getByRole("textbox", { name: "Patient’s full name" }).inputValue();
  expect(patientName.length).toBeGreaterThan(2);
  await expect(page.getByRole("spinbutton", { name: "Age in years" })).toHaveValue("58");
  await expect(page.getByRole("heading", { name: "Information in this record" })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  mkdirSync(evidence, { recursive: true });
  await page.screenshot({ path: `${evidence}/phone-returning-patient.png`, fullPage: true });
  await page.getByRole("button", { name: "Back", exact: true }).click();
  await page.getByRole("button", { name: /A child/ }).click();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Patient’s full name" })).toHaveValue("");
  await expect(page.getByRole("textbox", { name: "Your full name", exact: true })).toHaveValue(patientName);
  await expect(page.getByRole("heading", { name: "Information in this record" })).toHaveCount(0);
  expect(await page.evaluate(() => sessionStorage.length)).toBe(0);
  await page.screenshot({ path: `${evidence}/phone-dependent-separation.png`, fullPage: true });
});
