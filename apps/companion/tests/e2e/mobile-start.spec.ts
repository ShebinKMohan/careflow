import { mkdirSync } from "node:fs";
import type { Schema } from "@careflow/contracts";
import { expect, test } from "@playwright/test";

const evidence = new URL("../../../../docs/evidence/ADAPTIVE-20260928/fixtures/", import.meta.url).pathname;
test("phone creates an adaptive visit, preserves Back, answers the server question and reaches nurse review", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  let registrations = 0; let submitted: unknown; let intakeTurns = 0;
  const first = { question_id: "q_demo_1", key: "chief_complaint", text: "What brings you here today?", notice: null } satisfies Schema<"IntakeQuestion">;
  await page.route("**/v1/reception/directory", (route) => route.fulfill({ json: { hospital_name: "Northstar General Hospital", demo: true, notice: "Demo directory", departments: [] } satisfies Schema<"ReceptionDirectory"> }));
  await page.route("**/v1/checkin/adaptive", (route) => {
    registrations++; submitted = route.request().postDataJSON();
    expect(route.request().headers().authorization).toBeUndefined();
    return route.fulfill({ json: { session_id: "ses_adaptive_fixture", session_token: "phone-test-token", language: "en", patient_display: "D. E.", first_question: first } satisfies Schema<"CheckinResult"> });
  });
  await page.route("**/v1/sessions/ses_adaptive_fixture/status", (route) => route.fulfill({ json: { state: intakeTurns ? "awaiting_nurse" : "intake", current_question: intakeTurns ? null : first, intake_revision: intakeTurns ? null : 0 } }));
  await page.route("**/v1/sessions/*/turns", (route) => {
    intakeTurns++;
    expect(route.request().postDataJSON()).toMatchObject({ text: "My knee has been sore for two days", expected_intake_revision: 0 });
    return route.fulfill({ json: { done: true, next_question: null, intake_revision: null } });
  });
  await page.route("**/v1/sessions/*/intake-summary", (route) => route.fulfill({ json: { session_id: "ses_adaptive_fixture", visit_reference: "CF-FIXTURE-001", nurse_confirmed: false, assistance_requested: false, facts: [], alerts: [], suggestion: null, warnings: [] } }));
  await page.route("**/v1/sessions/*/reception", (route) => route.fulfill({ status: 404, json: {} }));
  await page.route("**/v1/companion/status", (route) => route.fulfill({ json: { state: "awaiting_nurse", room: null, position: null, wait_estimate_minutes: null, patient_type: "adult", token: null } satisfies Schema<"CompanionStatus"> }));
  await page.route("**/v1/ws-ticket", (route) => route.fulfill({ status: 503, json: { status: 503 } }));
  await page.goto("/start?l=en#t=clinic-entry-fixture-token");
  await expect(page.getByRole("heading", { name: "Welcome. Let’s find your details." })).toBeVisible();
  await expect(page).toHaveURL(/\/start\?l=en$/);
  await page.getByRole("button", { name: "Register as a new patient" }).click();
  await page.getByRole("button", { name: /Myself/ }).click();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("Patient’s full name", { exact: true }).fill("Demo Example");
  await page.getByLabel("Age in years", { exact: true }).fill("34");
  await page.getByRole("combobox", { name: "Sex", exact: true }).selectOption("female");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Back", exact: true }).click();
  await expect(page.getByLabel("Patient’s full name", { exact: true })).toHaveValue("Demo Example");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page.getByRole("button", { name: "Start my check-in" })).toBeDisabled();
  await page.getByRole("checkbox", { name: "I agree to use this patient’s details and answers for this visit." }).check();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  mkdirSync(evidence, { recursive: true });
  await page.screenshot({ path: `${evidence}/phone-consent.png`, fullPage: true });
  await page.getByRole("button", { name: "Start my check-in" }).click();
  await expect(page.getByRole("heading", { name: first.text })).toBeVisible();
  expect(registrations).toBe(1); expect(intakeTurns).toBe(0);
  expect(submitted).toMatchObject({ department_id: "unsure", visit_for: "self", patient: { name: "Demo Example", age_years: 34, sex: "female" }, consent: { camera: false, voice: false, data_use: true } });
  await page.screenshot({ path: `${evidence}/phone-question.png`, fullPage: true });
  await page.getByRole("textbox").fill("My knee has been sore for two days");
  await page.getByRole("button", { name: "Send", exact: true }).click();
  await page.getByRole("link", { name: "See my place in the queue" }).click();
  await expect(page.getByRole("heading", { name: "Waiting for nurse review" })).toBeVisible();
  expect(intakeTurns).toBe(1);
  await expect(page.getByText("CF-FIXTURE-001")).toBeVisible();
  await page.screenshot({ path: `${evidence}/phone-nurse-review.png`, fullPage: true });
  const saved = await page.evaluate(() => JSON.stringify({ ...sessionStorage }));
  expect(saved).not.toContain("Demo Example"); expect(saved).not.toContain("clinic-entry-fixture-token"); expect(saved).not.toContain("My knee");
});
