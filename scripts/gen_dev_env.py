#!/usr/bin/env python3
"""Fill missing local development secrets in the gitignored `.env`.

Every key in GENERATORS that is missing (or present with an empty value) gets a fresh random
value in the right format. Existing values are never changed and no value is ever printed.
Running it again changes nothing. Standard library only.

Only local, generated secrets live here. Vendor API keys are never generated: the owner may add
them by hand (names in `.env.example`); without them the local or replay provider is used.
"""

from __future__ import annotations

import argparse
import base64
import os
import re
import secrets
import subprocess
import sys
import tempfile
import uuid
from collections.abc import Callable
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
HEADER = (
    "# Local development secrets generated by scripts/gen_dev_env.py.\n"
    "# Gitignored. Never commit, paste or print these values.\n"
)
_LINE = re.compile(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$")


def _hex(nbytes: int) -> Callable[[], str]:
    return lambda: secrets.token_hex(nbytes)


def _password() -> str:
    return secrets.token_urlsafe(24)


def _b64(nbytes: int) -> Callable[[], str]:
    return lambda: base64.b64encode(secrets.token_bytes(nbytes)).decode("ascii")


def _fernet() -> str:
    return base64.urlsafe_b64encode(secrets.token_bytes(32)).decode("ascii")


def _whsec() -> str:  # Standard Webhooks secret format
    return "whsec_" + base64.b64encode(secrets.token_bytes(32)).decode("ascii")


# Key -> generator. Later issues append keys here (and their names to .env.example).
GENERATORS: dict[str, Callable[[], str]] = {
    # API auth (M0-07): JWT signing, seeded dev users, one-time WebSocket tickets.
    "CAREFLOW_JWT_SECRET": _hex(32),
    "CAREFLOW_DEV_PASSWORD": _password,
    "CAREFLOW_DEV_DEVICE_SECRET": _password,
    "CAREFLOW_WS_TICKET_SECRET": _hex(32),
    # Signing keys: QR hand-over tokens (M2-06), webhooks (M4-03), audit-chain anchors (M5-01).
    "CAREFLOW_HANDOVER_SIGNING_KEY": _hex(32),
    "CAREFLOW_WEBHOOK_SIGNING_SECRET": _whsec,
    "CAREFLOW_AUDIT_HMAC_KEY": _hex(32),
    # Encryption at rest: Fernet for application fields, pgcrypto for column encryption.
    "CAREFLOW_FERNET_KEY": _fernet,
    "CAREFLOW_PGCRYPTO_KEY": _hex(32),
    # Database role passwords (M0-05, M0-07).
    "POSTGRES_PASSWORD": _password,
    "CAREFLOW_DB_APP_PASSWORD": _password,
    "CAREFLOW_DB_MIGRATOR_PASSWORD": _password,
    "HAPI_DB_PASSWORD": _password,
    # Self-hosted Langfuse init (M5-05).
    "LANGFUSE_INIT_PROJECT_PUBLIC_KEY": lambda: f"pk-lf-{uuid.uuid4()}",
    "LANGFUSE_INIT_PROJECT_SECRET_KEY": lambda: f"sk-lf-{uuid.uuid4()}",
    "LANGFUSE_INIT_USER_PASSWORD": _password,
    "LANGFUSE_NEXTAUTH_SECRET": _b64(32),
    "LANGFUSE_SALT": _b64(32),
    "LANGFUSE_ENCRYPTION_KEY": _hex(32),
    "LANGFUSE_CLICKHOUSE_PASSWORD": _password,
    "LANGFUSE_MINIO_ROOT_PASSWORD": _password,
    "LANGFUSE_REDIS_AUTH": _password,
}


def parse_env(text: str) -> dict[str, str]:
    values: dict[str, str] = {}
    for line in text.splitlines():
        match = _LINE.match(line)
        if match:
            values[match.group(1)] = match.group(2).strip().strip("'\"")
    return values


def git_tracks_or_ignores(path: Path) -> str:
    """Return 'ignored', 'not-ignored' or 'no-repo' for `path`."""
    try:
        result = subprocess.run(  # noqa: S603 - fixed argv
            ["git", "check-ignore", "-q", path.name],  # noqa: S607 - git from PATH
            cwd=path.parent,
            capture_output=True,
            check=False,
        )
    except FileNotFoundError:
        return "no-repo"
    return {0: "ignored", 1: "not-ignored"}.get(result.returncode, "no-repo")


# Keys computed from other values (connection URLs built from the generated passwords).
DERIVED: dict[str, Callable[[dict[str, str]], str]] = {
    "DATABASE_URL": lambda v: (
        f"postgresql://careflow_app:{v['CAREFLOW_DB_APP_PASSWORD']}@localhost:5432/careflow"
    ),
    "DATABASE_URL_MIGRATOR": lambda v: (
        f"postgresql://careflow_migrator:{v['CAREFLOW_DB_MIGRATOR_PASSWORD']}@localhost:5432/careflow"
    ),
    "REDIS_URL": lambda _: "redis://localhost:6379/0",
    "FHIR_BASE_URL": lambda _: "http://localhost:8080/fhir",
}


def _set(lines: list[str], existing: dict[str, str], key: str, value: str) -> list[str]:
    if key in existing:  # present with an empty value (e.g. copied from .env.example)
        return [
            f"{key}={value}" if (m := _LINE.match(line)) and m.group(1) == key else line
            for line in lines
        ]
    return [*lines, f"{key}={value}"]


def fill(text: str) -> tuple[str, list[str]]:
    """Return the new file text and the names of the keys that were added or filled."""
    existing = parse_env(text)
    values = dict(existing)
    changed: list[str] = []
    lines = text.splitlines()
    for key, generate in GENERATORS.items():
        if not existing.get(key):
            values[key] = generate()
            lines = _set(lines, existing, key, values[key])
            changed.append(key)
    for key, derive in DERIVED.items():
        if not existing.get(key):
            values[key] = derive(values)
            lines = _set(lines, existing, key, values[key])
            changed.append(key)
    new_text = "\n".join(lines) + "\n" if lines else ""
    if not text:
        new_text = HEADER + new_text
    return new_text, changed


def write_private(path: Path, text: str) -> None:
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".env.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.chmod(tmp, 0o600)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Fill missing local dev secrets in .env.")
    parser.add_argument("--env-file", type=Path, default=REPO_ROOT / ".env")
    args = parser.parse_args(argv)
    env_file: Path = args.env_file.resolve()

    if git_tracks_or_ignores(env_file) == "not-ignored":
        print(f"gen_dev_env: refusing: {env_file.name} is not gitignored.", file=sys.stderr)
        return 1

    text = env_file.read_text(encoding="utf-8") if env_file.exists() else ""
    new_text, changed = fill(text)
    if not changed:
        count = len(GENERATORS) + len(DERIVED)
        print(f"gen_dev_env: no changes ({count} keys already set in {env_file.name}).")
        return 0
    write_private(env_file, new_text)
    print(f"gen_dev_env: set {len(changed)} key(s) in {env_file.name}: {', '.join(changed)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
